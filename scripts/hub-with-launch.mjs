import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {createPublicClient,keccak256} from 'viem';
import {robinhood} from 'viem/chains';
import {getSharedReliableRpc,rpcOptionsFromEnv} from '../dist/rpc.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const launchRoot=path.resolve(process.env.HUB_LAUNCHPAD_PATH||path.join(root,'../robinhood-launchpad'));
const manifest=JSON.parse(fs.readFileSync(path.join(launchRoot,'deployments/4663.json'),'utf8'));
const reviewed='0xafa9dfc1834a2363469b608d5d5daa3e60cd5d3ec24208b91a5b1845a5b309c7';
if(manifest.chainId!==4663||manifest.buildHash!==reviewed)throw new Error('Deployment manifest is not the reviewed mainnet build.');
if(manifest.deployer.toLowerCase()!=='0xb50516982524dff3d8d563f46ad54891aa61944e')throw new Error('Unexpected factory deployer.');
const artifacts=Object.fromEntries(['LaunchFactory','TokenFactory'].map(name=>[name,JSON.parse(fs.readFileSync(path.join(launchRoot,'artifacts',name+'.json'),'utf8'))]));
if(keccak256(artifacts.LaunchFactory.bytecode)!==reviewed)throw new Error('Launchpad artifacts changed.');
const {verifyFactory}=await import(pathToFileURL(path.join(launchRoot,'scripts/live-operations.mjs')).href);
if(process.env.HOOD_NETWORK&&process.env.HOOD_NETWORK!=='mainnet')throw new Error('Use mainnet for this verified deployment.');
const rpc=getSharedReliableRpc(rpcOptionsFromEnv({...process.env,HOOD_NETWORK:'mainnet'}));
const client=createPublicClient({chain:robinhood,transport:rpc.transport,cacheTime:0});
if(await client.getChainId()!==4663)throw new Error('RPC chain mismatch.');
const receipt=await client.waitForTransactionReceipt({hash:manifest.transactionHash,confirmations:2,timeout:60000});
const tx=await client.getTransaction({hash:manifest.transactionHash});
const block=await client.getBlock({blockNumber:receipt.blockNumber});
if(receipt.status!=='success'||receipt.contractAddress?.toLowerCase()!==manifest.factory.toLowerCase()||receipt.blockNumber.toString()!==manifest.blockNumber||block.hash!==receipt.blockHash||
 tx.from.toLowerCase()!==manifest.deployer.toLowerCase()||tx.to!==null||tx.value!==0n||keccak256(tx.input)!==reviewed)throw new Error('Deployment receipt does not match its manifest.');
const verified=await verifyFactory(client,manifest.factory,artifacts);
if(verified.tokenFactory.toLowerCase()!==manifest.tokenFactory.toLowerCase()||verified.runtimeHash!==manifest.runtimeHash||verified.tokenFactoryRuntimeHash!==manifest.tokenFactoryRuntimeHash)throw new Error('Factory runtime manifest mismatch.');
if(process.env.HOOD_NETWORK&&process.env.HOOD_NETWORK!=='mainnet')throw new Error('Use mainnet for this verified deployment.');
if(process.env.HUB_LAUNCH_FACTORY_ADDRESS&&process.env.HUB_LAUNCH_FACTORY_ADDRESS.toLowerCase()!==manifest.factory.toLowerCase())throw new Error('Conflicting factory configuration.');
process.env.HOOD_NETWORK='mainnet';
process.env.HUB_LAUNCH_FACTORY=manifest.factory;
process.env.HUB_LAUNCH_FACTORY_BLOCK=manifest.blockNumber;
console.log('Verified LaunchFactory '+manifest.factory+' at block '+manifest.blockNumber+'. Starting the existing paper Hub.');
await import(pathToFileURL(path.join(root,'dist/hub-main.js')).href);
